void ADAU1761_I2C_Write(u8 device_addr,u16 reg_addr,u16 *data,u16 length)
{
	u32 i;
	u8 temp;
	
	// start
	GPIO_I2C_Start();
	// w device_addr
	GPIO_I2C_SendByte(device_addr);
	// wait ack
	A2B_I2C_WaitACK();
	// w reg_addr H
	GPIO_I2C_SendByte(MSB(reg_addr));
	// wait ack
	A2B_I2C_WaitACK();
	// w reg_addr L
	GPIO_I2C_SendByte(LSB(reg_addr));
	// wait ack
	A2B_I2C_WaitACK();
	
	for(i=0;i<length;i++)
	{
		temp=data[i];
		// w reg_value
		GPIO_I2C_SendByte(temp);
		// wait ack
		A2B_I2C_WaitACK();
	}
	GPIO_I2C_Stop();	
}

void ADAU1761_LoadParam(u8 device_addr,u16 *data,u32 size)
{
	u32 i;
	u32 length;
	u16 reg_addr;
	u16 *ptr;

	ptr=data;
	for(i=0;i<size;)
	{
		length=*ptr;
		ptr++;
		reg_addr=*ptr;
		ptr++;
		ADAU1761_I2C_Write(device_addr,reg_addr,ptr,length);
		ptr+=length;
		i+=(length+2);
	}
}

